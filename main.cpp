#include <string>
#include <vector>

void sum_evens() {
    int values[5] = {2, 4, 6, 8, 10};
    int acc = 0;
    for (int i = 0; i < 5; ++i) acc += values[i];
    (void)acc;
}

void swap_values() {
    int a = 5, b = 11;
    int tmp = a;
    a = b;
    b = tmp;
    (void)a;
    (void)b;
}

void count_vowels() {
    std::string text = "prism bridge";
    int vowels = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        char ch = text[i];
        if (ch == 'a' || ch == 'e' || ch == 'i' || ch == 'o' || ch == 'u') vowels += 1;
    }
    (void)vowels;
}

void greatest_divisor() {
    int a = 48, b = 18;
    while (b != 0) {
        int t = a % b;
        a = b;
        b = t;
    }
    (void)a;
}

extern "C" int lucid_boulder();
extern "C" void bright_grove();
extern "C" void subtle_marble();
extern "C" void noble_thorn();

int main() {
    sum_evens();
    swap_values();
    count_vowels();
    greatest_divisor();
    bright_grove();
    subtle_marble();
    noble_thorn();
    return lucid_boulder();
}
